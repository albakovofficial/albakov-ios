import Foundation

/// Данные покупателя, которые хранятся только на телефоне (UserDefaults) и стираются при выходе и удалении аккаунта
/// (Shop.forgetUser; счётчик мерок при этом не стирается, а увеличивается): черновик оформления — имя, телефон, почта, адрес (аудит F-1) — и мерки для подбора размера — рост,
/// вес, посадка, свои замеры, как «albakov:fit» на сайте (L8-11). Ключи — в ядре: экраны оформления и подбора размера
/// читают и пишут по ним, а ядро стирает, не завися от экранов (L8-23)
enum DeviceData {
    static let checkoutDraft = "checkoutDraft"
    static let fit = "fit"
    /// Счётчик изменений мерок: экраны размера следят за ним (@AppStorage) и перечитывают мерки
    static let fitTick = "fitTick"
}
